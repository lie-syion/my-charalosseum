# ---------------------------------------------------------------- 사용자 프리셋 병합


def _load_user_presets() -> Dict[str, Any]:
    path = DATA_DIR / "user_presets.json"
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _merge():
    user = _load_user_presets()
    for key, target in (
        ("environments", ENVIRONMENTS),
        ("modifiers", MODIFIERS),
        ("tones", TONES),
    ):
        for item in user.get(key, []):
            if isinstance(item, dict) and item.get("name"):
                target.append({"name": item["name"], "desc": item.get("desc", "")})


_merge()


def scale_by_key(key: str) -> Dict[str, Any]:
    for s in SCALES:
        if s["key"] == key:
            return s
    return SCALES[0]
